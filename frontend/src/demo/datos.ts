import { ATRIBUTOS_ACCESIBILIDAD, type Accesibilidad, type DatoAccesibilidad, type Destino, type EstadoAtributo, type POIDetalle } from '../api/tipos'

type Corto = [valor: DatoAccesibilidad['valor'], estado: EstadoAtributo, origen?: string, fecha?: string]

/** Arma la accesibilidad con la forma del contrato: los 9 atributos, `si`/`no` y números en texto. */
function a(datos: Partial<Record<keyof Accesibilidad, Corto>>): Accesibilidad {
  const resultado: Accesibilidad = {}
  for (const atributo of ATRIBUTOS_ACCESIBILIDAD) {
    const corto = datos[atributo]
    if (!corto || corto[0] === null) {
      resultado[atributo] = { valor: null, estado: corto?.[1] ?? 'sin_verificar', origen: null, confianza: null, fecha: null }
      continue
    }
    const [valor, estado, origen = 'demostracion', fecha = '2026-10-01'] = corto
    resultado[atributo] = {
      valor: typeof valor === 'boolean' ? (valor ? 'si' : 'no') : typeof valor === 'number' ? String(valor) : valor,
      estado,
      origen,
      confianza: estado === 'verificado' ? 0.9 : 0.5,
      fecha,
    }
  }
  return resultado
}

